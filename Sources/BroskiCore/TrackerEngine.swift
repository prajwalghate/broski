// MARK: Globs and JSON paths

enum Glob {
    /// "tracker/findings/*.md", "register/items/{T,R,F}-*.md", "docs/**/*.md".
    static func regex(_ glob: String) -> NSRegularExpression? {
        var out = "^"
        var i = glob.startIndex
        var braces = 0
        while i < glob.endIndex {
            let ch = glob[i]
            let next = glob.index(after: i)
            switch ch {
            case "*":
                if next < glob.endIndex, glob[next] == "*" {
                    let after = glob.index(after: next)
                    if after < glob.endIndex, glob[after] == "/" {
                        out += "(?:.*/)?"
                        i = glob.index(after: after)
                    } else {
                        out += ".*"
                        i = after
                    }
                    continue
                }
                out += "[^/]*"
            case "?": out += "[^/]"
            case "{": braces += 1; out += "(?:"
            case "}": braces -= 1; out += ")"
            case ",": out += braces > 0 ? "|" : ","
            case ".", "(", ")", "+", "|", "^", "$", "[", "]", "\\": out += "\\" + String(ch)
            default: out.append(ch)
            }
            i = next
        }
        return try? NSRegularExpression(pattern: out + "$", options: [.caseInsensitive])
    }

    static func matches(_ path: String, _ glob: String) -> Bool {
        guard let re = regex(glob) else { return false }
        return re.firstMatch(in: path, range: NSRange(path.startIndex..., in: path)) != nil
    }
}

enum JSONPath {
    /// Objects at a path like "value.phases[].actions[]", each with its parent's scalar fields (for context).
    static func select(_ json: Any, _ path: String) -> [(object: [String: Any], parent: [String: Any])] {
        var current: [(Any, [String: Any])] = [(json, [:])]
        for raw in path.split(separator: ".").map(String.init) where !raw.isEmpty {
            let flatten = raw.hasSuffix("[]")
            let key = flatten ? String(raw.dropLast(2)) : raw
            var next: [(Any, [String: Any])] = []
            for (value, parent) in current {
                guard let dict = value as? [String: Any] else { continue }
                // A dataset without the {value} envelope: skip a missing "value" step.
                let inner = key == "value" && dict["value"] == nil ? dict : dict[key]
                guard let inner else { continue }
                let scalars = dict.filter { !($0.value is [Any]) && !($0.value is [String: Any]) }
                if flatten, let array = inner as? [Any] {
                    next += array.map { ($0, scalars) }
                } else if flatten, let map = inner as? [String: Any] {
                    next += map.map { (k, v) in
                        var object = (v as? [String: Any]) ?? ["value": v]
                        if object["id"] == nil { object["id"] = k }
                        return (object, scalars)
                    }
                } else {
                    next.append((inner, parent))
                }
            }
            current = next
        }
        return current.compactMap { value, parent in (value as? [String: Any]).map { ($0, parent) } }
    }
}

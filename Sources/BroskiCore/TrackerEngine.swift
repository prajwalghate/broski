import Foundation

// MARK: Canonical status

/// The status vocabulary every tracker maps onto. The tracker's own word is kept too (`TrackerRecord.status`).
public enum CanonicalStatus: String, Codable, CaseIterable {
    case open, doing, blocked, done, wontfix, accepted, decided, superseded
    /// Messages: not yet acknowledged / acknowledged.
    case unread, read
    /// State the tracker derives live (plan steps, tests): Broski never guesses it from files.
    case live
    /// No status: docs, procedures, reference data.
    case none

    public var isOpen: Bool { self == .open || self == .doing || self == .blocked || self == .unread }

    /// Native word → canonical, for words most trackers use. A manifest's statusMap overrides it.
    public static func from(_ native: String) -> CanonicalStatus {
        words[native.lowercased().trimmingCharacters(in: .whitespaces)] ?? .open
    }

    /// Whether `from` knows the word. An unknown word still reads as open, so drift lists it for the threads to map.
    public static func isKnown(_ native: String) -> Bool {
        words[native.lowercased().trimmingCharacters(in: .whitespaces)] != nil
    }

    private static let words: [String: CanonicalStatus] = {
        let groups: [(CanonicalStatus, [String])] = [
            (.none, [""]),
            (.open, ["open", "todo", "to do", "new", "triage", "proposed", "planned", "pending", "waiting", "active", "assigned", "ready"]),
            (.doing, ["doing", "in-progress", "in progress", "wip", "running", "started"]),
            (.blocked, ["blocked", "on hold", "paused"]),
            (.done, ["done", "closed", "resolved", "fixed", "solved", "complete", "completed", "shipped", "released", "verified", "mitigated", "passed"]),
            (.wontfix, ["wontfix", "won't fix", "rejected", "cancelled", "canceled", "dropped", "obsolete", "withdrawn", "retired", "duplicate", "called-off"]),
            (.accepted, ["accepted", "design", "known"]),
            (.decided, ["decided"]),
            (.superseded, ["superseded"]),
            (.unread, ["unread"]),
            (.read, ["read"]),
        ]
        var map: [String: CanonicalStatus] = [:]
        for (status, list) in groups { for word in list { map[word] = status } }
        return map
    }()
}

// MARK: Manifest

/// How Broski reads one tracker: which files feed which core section, how statuses map, what to skip.
/// Lives as `broski.json` in the tracker, or as an overlay in Broski's own folder (`trackers/<id>.broski.json`)
/// when the tracker can't take a file yet. Without either, Broski uses a preset for the tracker's shape.
public struct TrackerManifest: Codable, Equatable {
    public struct Source: Codable, Equatable {
        /// fm-records | json-records | json-doc | jsonl-records | md-sections | md-checklist | md-doc
        public var reader: String
        public var glob: String?
        public var file: String?
        /// JSON path for json readers: "value.decisions[]", "value.phases[].actions[]".
        public var path: String?
        public var kind: String?
        /// Take the kind from this field ("kind" in strado's items).
        public var kindFrom: String?
        /// Only records whose field equals the value ("category": "ops").
        public var filter: [String: String]?
        /// canonical field → native field ("title": "question").
        public var map: [String: String]?
        /// Launch slug for plan steps.
        public var launch: String?
        /// Heading level for md-sections (2 by default).
        public var level: Int?
        /// Id pattern for md-checklist lines.
        public var idPattern: String?
        public var archived: Bool?
        /// State is live-only (plan steps, tests): never derived from files.
        public var live: Bool?

        public init(reader: String, glob: String? = nil, file: String? = nil, path: String? = nil, kind: String? = nil,
                    kindFrom: String? = nil, filter: [String: String]? = nil, map: [String: String]? = nil, launch: String? = nil,
                    level: Int? = nil, idPattern: String? = nil, archived: Bool? = nil, live: Bool? = nil) {
            self.reader = reader
            self.glob = glob
            self.file = file
            self.path = path
            self.kind = kind
            self.kindFrom = kindFrom
            self.filter = filter
            self.map = map
            self.launch = launch
            self.level = level
            self.idPattern = idPattern
            self.archived = archived
            self.live = live
        }
    }

    public struct Layer: Codable, Equatable {
        public var name: String
        public var title: String
        public var sources: [Source]
        /// Generated by a tool: index what it is, never retype its numbers.
        public var derived: Bool?

        public init(name: String, title: String, sources: [Source], derived: Bool? = nil) {
            self.name = name
            self.title = title
            self.sources = sources
            self.derived = derived
        }
    }

    public struct Board: Codable, Equatable {
        public var url: String
        /// Deep link patterns by kind: {"finding": "#/register/{id}"}.
        public var links: [String: String]?

        public init(url: String, links: [String: String]? = nil) {
            self.url = url
            self.links = links
        }
    }

    public var broski: Int = 1
    /// Short id used in citations ("one" → [[one:DEC-70]]).
    public var id: String
    public var title: String
    public var adapter: String
    /// Read a git ref's snapshot ("main") instead of the working tree. Ignored where git isn't available.
    public var readFrom: String?
    /// Other repos by alias, for sources like "@app:vmhandbook.md" (paths relative to the tracker root or absolute).
    public var repos: [String: String]?
    /// Person key → the words records use for them ("owner": ["you", "founder"]).
    public var people: [String: [String]]?
    public var core: [String: [Source]]
    public var layers: [Layer]?
    /// native → canonical overrides ("solved": "done").
    public var statusMap: [String: String]?
    /// When set, only these native words count as open for items (a tracker where only "open" means open).
    public var openWhen: [String]?
    /// Docs known to drift: answers never take counts or state from them.
    public var lowTrust: [String]?
    public var exclude: [String]?
    /// Dataset names that are generated: indexed as metadata only.
    public var generated: [String]?
    /// Dataset names that are history: indexed, flagged archived, left out of default answers.
    public var archived: [String]?
    public var board: Board?
    /// Regexes whose matches are redacted from everything indexed.
    public var redact: [String]?

    public init(id: String, title: String, adapter: String, readFrom: String? = nil, repos: [String: String]? = nil,
                people: [String: [String]]? = nil, core: [String: [Source]], layers: [Layer]? = nil, statusMap: [String: String]? = nil,
                openWhen: [String]? = nil, lowTrust: [String]? = nil, exclude: [String]? = nil, generated: [String]? = nil,
                archived: [String]? = nil, board: Board? = nil, redact: [String]? = nil) {
        self.id = id
        self.title = title
        self.adapter = adapter
        self.readFrom = readFrom
        self.repos = repos
        self.people = people
        self.core = core
        self.layers = layers
        self.statusMap = statusMap
        self.openWhen = openWhen
        self.lowTrust = lowTrust
        self.exclude = exclude
        self.generated = generated
        self.archived = archived
        self.board = board
        self.redact = redact
    }

    public static let fileName = "broski.json"

    /// The overlay file for a source id ("tamer/Tamer" → "tamer__Tamer.broski.json").
    public static func overlayName(_ id: String, draft: Bool = false) -> String {
        id.replacingOccurrences(of: "/", with: "__") + (draft ? ".broski.draft.json" : ".\(fileName)")
    }

    /// The manifest for a tracker: an overlay in Broski's folder, else `broski.json` in the tracker, else a preset.
    public static func resolve(for source: TrackerSource, overlays: URL?) -> TrackerManifest {
        let decoder = JSONDecoder()
        if let overlays, let data = try? Data(contentsOf: overlays.appendingPathComponent(overlayName(source.id))),
           let manifest = try? decoder.decode(TrackerManifest.self, from: data) { return manifest }
        if source.scope == .tracker {
            for candidate in [source.url.appendingPathComponent(fileName), source.url.appendingPathComponent("tracker/\(fileName)")] {
                if let data = try? Data(contentsOf: candidate), let manifest = try? decoder.decode(TrackerManifest.self, from: data) { return manifest }
            }
        }
        return TrackerPresets.detect(source)
    }
}

// MARK: Presets

/// Ready-made manifests for common tracker shapes. A project with its own shape keeps its manifest as an overlay in
/// Broski's folder (`trackers/<id>.broski.json`; `--export-manifest` writes one to start from).
public enum TrackerPresets {
    /// Picks a preset from what's in the folder.
    public static func detect(_ source: TrackerSource) -> TrackerManifest {
        let fm = FileManager.default
        let root = source.url
        func has(_ path: String) -> Bool { fm.fileExists(atPath: root.appendingPathComponent(path).path) }
        if source.scope == .docs { return genericMarkdown(id: source.id, title: source.name, docsOnly: true) }
        if has("register/items") { return registerItems(id: source.id, title: source.name, board: source.board) }
        if has("WORK-BOARD.md") { return workBoard(id: source.id, title: source.name) }
        if has("ship") || has("items") || has("decisions") { return broskiTracker(id: source.id, title: source.name) }
        return genericMarkdown(id: source.id, title: source.name, docsOnly: false)
    }

    /// A register: one item per file with a `kind`, decisions as their own files, and a phase plan.
    public static func registerItems(id: String, title: String, board: String?) -> TrackerManifest {
        typealias S = TrackerManifest.Source
        return TrackerManifest(
            id: id, title: title, adapter: "register-items",
            people: ["owner": ["you", "founder"], "claude": ["claude"]],
            core: [
                "findings": [S(reader: "fm-records", glob: "register/items/{T,R,F}-*.md", kindFrom: "kind")],
                "decisions": [S(reader: "fm-records", glob: "register/items/DEC-*.md", kind: "decision", map: ["date": "decided_at"])],
                "ship": [S(reader: "json-records", file: "data/plan.json", path: "phases[]", kind: "milestone", map: ["title": "name"])],
            ],
            layers: [
                .init(name: "research", title: "Research", sources: [S(reader: "md-sections", glob: "docs/research/*.md", kind: "doc")]),
                .init(name: "docs", title: "Docs", sources: [S(reader: "md-sections", glob: "{README.md,docs/VISION.md}", kind: "doc")]),
            ],
            statusMap: ["todo": "open", "dropped": "wontfix", "mitigated": "done", "closed": "done"],
            lowTrust: ["README.md"],
            exclude: ["node_modules/**", "web/**", "src/**", "tools/**", "test/**"],
            board: board.map { .init(url: $0, links: nil) })
    }

    /// One big WORK-BOARD.md: checklist tasks, a work log, a verified lane.
    public static func workBoard(id: String, title: String) -> TrackerManifest {
        typealias S = TrackerManifest.Source
        return TrackerManifest(
            id: id, title: title, adapter: "work-board",
            people: ["owner": ["founder", "brain", "you"], "claude": ["hands", "claude", "develop"]],
            core: [
                "findings": [S(reader: "md-checklist", file: "WORK-BOARD.md", kind: "task", idPattern: "\\b(T\\d+[a-z]?|S\\d+·\\d+)\\b")],
                "ops": [S(reader: "md-sections", glob: "{DEPLOY.md,DEPLOYMENT.md,docs/*DEPLOY*.md,docs/*RUNBOOK*.md,*RUNBOOK*.md}", kind: "runbook")],
                "launch": [S(reader: "md-sections", glob: "{docs/LAUNCH*.md,docs/*LAUNCH*.md,LAUNCH*.md}", kind: "doc")],
                "decisions": [S(reader: "md-sections", glob: "{DECISIONS.md,docs/DECISIONS.md,docs/adr/*.md}", kind: "decision")],
            ],
            layers: [.init(name: "docs", title: "Docs", sources: [S(reader: "md-sections", glob: "{README.md,AGENTS.md,CLAUDE.md,docs/*.md}", kind: "doc")])],
            lowTrust: ["README.md", "docs/*.md"],
            exclude: ["node_modules/**", ".claude/**", "_to_delete/**"])
    }

    /// Any repo: decisions, findings, runbooks and launch docs found by name; everything else as docs.
    public static func genericMarkdown(id: String, title: String, docsOnly: Bool) -> TrackerManifest {
        typealias S = TrackerManifest.Source
        // Top-level docs, doc folders, and (for a folder of projects) each sub-project's README and docs.
        let docs = "{*.md,docs/**/*.md,doc/**/*.md,notes/**/*.md,research/**/*.md,ops/**/*.md,plans/**/*.md,design/**/*.md,specs/**/*.md,*/README.md,*/*.md,*/docs/**/*.md}"
        return TrackerManifest(
            id: id, title: title, adapter: "generic-markdown",
            core: [
                "decisions": [S(reader: "md-sections", glob: "{DECISIONS.md,docs/DECISIONS.md,docs/adr/*.md,docs/adrs/*.md,decisions/*.md}", kind: "decision")],
                "findings": [S(reader: "md-sections", glob: "{FINDINGS.md,docs/FINDINGS.md}", kind: "finding"),
                             S(reader: "md-checklist", glob: "{WORK-BOARD.md,TODO.md,docs/TODO.md}", kind: "task", idPattern: "\\b(T\\d+[a-z]?|S\\d+·\\d+)\\b")],
                "ops": [S(reader: "md-sections", glob: "{*DEPLOY*.md,docs/*DEPLOY*.md,*RUNBOOK*.md,docs/*RUNBOOK*.md,docs/*runbook*.md,*HANDOFF*.md,*HANDOVER*.md}", kind: "runbook")],
                "launch": [S(reader: "md-sections", glob: "{*LAUNCH*.md,docs/*LAUNCH*.md,docs/*launch*.md}", kind: "doc")],
                "ship": [S(reader: "md-sections", glob: "{CHANGELOG.md,RELEASING.md,DEVELOPMENT_STATUS.md,docs/sprints/*.md}", kind: "doc")],
            ],
            layers: [.init(name: "docs", title: docsOnly ? "Docs" : "Docs", sources: [S(reader: "md-sections", glob: docs, kind: "doc")])],
            lowTrust: ["README.md", "docs/**"],
            exclude: ["node_modules/**", ".claude/**", "_to_delete/**", "**/worktrees/**", "backup/**", "vendor/**", "Pods/**", "build/**", "dist/**"])
    }

    /// A tracker made from Broski's template.
    public static func broskiTracker(id: String, title: String) -> TrackerManifest {
        typealias S = TrackerManifest.Source
        return TrackerManifest(
            id: id, title: title, adapter: "broski-tracker",
            people: ["owner": ["you", "founder"], "claude": ["claude"]],
            core: [
                "findings": [S(reader: "fm-records", glob: "items/*.md", kindFrom: "kind")],
                "decisions": [S(reader: "fm-records", glob: "decisions/*.md", kind: "decision", map: ["title": "question"])],
                "ship": [S(reader: "md-sections", file: "ship/PLAN.md", kind: "milestone"), S(reader: "fm-records", glob: "ship/releases/*.md", kind: "release")],
                "launch": [S(reader: "md-checklist", glob: "launch/*.md", kind: "step", idPattern: "\\b(L-\\d+)\\b")],
                "ops": [S(reader: "fm-records", glob: "ops/runbooks/*.md", kind: "runbook"), S(reader: "fm-records", glob: "ops/incidents/*.md", kind: "incident"),
                        S(reader: "md-sections", glob: "ops/journal/*.md", kind: "journal")],
                "threads": [S(reader: "md-sections", file: "threads/THREADS.md", kind: "doc")],
            ],
            layers: [.init(name: "brief", title: "Brief", sources: [S(reader: "md-sections", glob: "{TRACKER.md,VISION.md}", kind: "doc")]),
                     .init(name: "layers", title: "Layers", sources: [S(reader: "md-sections", glob: "layers/*/*.md", kind: "doc")])])
    }
}

// MARK: Reading files

/// Where a tracker's files come from: the working tree, or a git snapshot of a ref (so a sync mid-read can't
/// give a half-updated state, and uncommitted edits are left out).
protocol TrackerFS {
    var files: [String] { get }
    var revision: String? { get }
    func read(_ path: String) -> Data?
    func modified(_ path: String) -> Date?
}

/// Paths Broski never reads, whatever a manifest says.
enum Forbidden {
    static func contains(_ path: String) -> Bool {
        let name = (path as NSString).lastPathComponent.lowercased()
        if name.hasPrefix(".env") || name.hasSuffix(".db") || name.contains(".db-") || name.hasSuffix(".sqlite")
            || name.hasSuffix(".pem") || name.hasSuffix(".key") || name.hasSuffix(".p12") || name == "secrets.json" { return true }
        return false
    }
}

final class WorkingTreeFS: TrackerFS {
    let root: URL
    let files: [String]
    var revision: String? { nil }
    static let skipped: Set<String> = ["node_modules", ".git", "backup", "backups", ".build", "build", "dist", "worktrees", ".claude",
                                       "pods", ".venv", "venv", "__pycache__", "_to_delete", "trash", "vendor"]

    /// `docsOnly`: a code repo read for its docs: shallow, and data/log folders skipped.
    init(root: URL, docsOnly: Bool = false) {
        self.root = root
        let maxDepth = docsOnly ? 4 : 6
        let extraSkips: Set<String> = docsOnly ? ["data", "logs", "log", "archive", "receipts", "fixtures", "assets", "public", "static", "migrations", "snapshots"] : []
        var out: [String] = []
        let fm = FileManager.default
        // The walker may report the real path (/private/var/…) of a root given through a symlink (/var, /tmp),
        // so relative paths are cut from whichever form of the root the reported path starts with.
        let given = root.standardizedFileURL.path
        let real = given.withCString { realpath($0, nil) }.map { pointer -> String in defer { free(pointer) }; return String(cString: pointer) } ?? given
        let prefixes = Set([given, real]).map { $0.hasSuffix("/") ? $0 : $0 + "/" }
        if let walker = fm.enumerator(at: root, includingPropertiesForKeys: [.isDirectoryKey, .fileSizeKey], options: [.skipsHiddenFiles]) {
            for case let url as URL in walker {
                guard let prefix = prefixes.first(where: { url.path.hasPrefix($0) }) else { continue }
                let relative = String(url.path.dropFirst(prefix.count))
                let depth = relative.split(separator: "/").count
                let values = try? url.resourceValues(forKeys: [.isDirectoryKey, .fileSizeKey])
                if values?.isDirectory == true {
                    let name = url.lastPathComponent.lowercased()
                    if Self.skipped.contains(name) || extraSkips.contains(name) || depth > maxDepth {
                        walker.skipDescendants()
                    }
                    continue
                }
                let ext = url.pathExtension.lowercased()
                guard ["md", "json", "jsonl", "tsv"].contains(ext), (values?.fileSize ?? 0) <= 4_000_000 else { continue }
                if !Forbidden.contains(relative) { out.append(relative) }
            }
        }
        files = out.sorted()
    }

    func read(_ path: String) -> Data? {
        guard !Forbidden.contains(path) else { return nil }
        return try? Data(contentsOf: root.appendingPathComponent(path))
    }

    func modified(_ path: String) -> Date? {
        (try? root.appendingPathComponent(path).resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate
    }
}

#if os(macOS)
/// A git ref's tree, read with plumbing only (rev-parse, ls-tree, cat-file). Never fetches, never writes.
final class GitSnapshotFS: TrackerFS {
    let root: URL
    let files: [String]
    let revision: String?
    private var cache: [String: Data] = [:]
    private var dates: [String: Date] = [:]

    init?(root: URL, ref: String) {
        self.root = root
        guard let sha = Self.git(root, ["rev-parse", "--verify", "--quiet", "\(ref)^{commit}"]).flatMap({ String(data: $0, encoding: .utf8) })?
            .trimmingCharacters(in: .whitespacesAndNewlines), !sha.isEmpty else { return nil }
        revision = sha
        guard let list = Self.git(root, ["ls-tree", "-r", "-z", "--name-only", sha]) else { return nil }
        let all = list.split(separator: 0).compactMap { String(data: Data($0), encoding: .utf8) }
        files = all.filter { path in
            let ext = (path as NSString).pathExtension.lowercased()
            return ["md", "json", "jsonl", "tsv"].contains(ext) && !Forbidden.contains(path)
                && !path.hasPrefix("node_modules/") && !path.hasPrefix("backup/")
        }.sorted()
    }

    /// Reads many files in one `git cat-file --batch`.
    func preload(_ paths: [String]) {
        let wanted = paths.filter { cache[$0] == nil && !Forbidden.contains($0) }
        guard let revision, !wanted.isEmpty else { return }
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/git")
        process.arguments = ["-C", root.path, "--no-optional-locks", "cat-file", "--batch"]
        let input = Pipe(), output = Pipe()
        process.standardInput = input
        process.standardOutput = output
        process.standardError = FileHandle.nullDevice
        do { try process.run() } catch { return }
        let request = wanted.map { "\(revision):\($0)\n" }.joined()
        DispatchQueue.global().async {
            input.fileHandleForWriting.write(Data(request.utf8))
            try? input.fileHandleForWriting.close()
        }
        let data = output.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()
        var offset = data.startIndex
        for path in wanted {
            guard let newline = data[offset...].firstIndex(of: 10) else { break }
            let header = String(decoding: data[offset..<newline], as: UTF8.self).split(separator: " ")
            offset = data.index(after: newline)
            guard header.count == 3, header[1] == "blob", let size = Int(header[2]) else { continue }
            let end = data.index(offset, offsetBy: size)
            cache[path] = data[offset..<end]
            offset = data.index(after: end)
        }
    }

    func read(_ path: String) -> Data? {
        guard !Forbidden.contains(path) else { return nil }
        if cache[path] == nil { preload([path]) }
        return cache[path]
    }

    func modified(_ path: String) -> Date? {
        if let date = dates[path] { return date }
        guard let revision, let out = Self.git(root, ["log", "-1", "--format=%cI", revision, "--", path]),
              let date = TrackerReader.parseDate(String(decoding: out, as: UTF8.self)) else { return nil }
        dates[path] = date
        return date
    }

    /// Last commit date for many paths at once (one `git log`, newest first).
    func preloadDates(since: String = "2026-01-01") {
        guard let revision, let out = Self.git(root, ["log", "--format=@%cI", "--name-only", "--since=\(since)", revision]) else { return }
        var current: Date?
        for line in String(decoding: out, as: UTF8.self).split(separator: "\n") {
            if line.hasPrefix("@") { current = TrackerReader.parseDate(String(line.dropFirst())) }
            else if let current, dates[String(line)] == nil { dates[String(line)] = current }
        }
    }

    static func git(_ root: URL, _ args: [String]) -> Data? {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/git")
        process.arguments = ["-C", root.path, "--no-optional-locks"] + args
        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = FileHandle.nullDevice
        do { try process.run() } catch { return nil }
        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()
        return process.terminationStatus == 0 ? data : nil
    }
}

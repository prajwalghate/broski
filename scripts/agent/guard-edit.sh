#!/bin/bash
# PreToolUse hook for Edit, Write and NotebookEdit (.claude/settings.json): files agents don't change, and the
# guardrails a person approves changes to. Tested by scripts/agent/test-hooks.sh. Reads the hook's JSON on stdin.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

input="$(cat)"
path="$(jq -r '.tool_input.file_path // .tool_input.notebook_path // ""' <<<"$input" 2>/dev/null)"
[[ -z "$path" ]] && exit 0
if [[ "$path" != /* ]]; then
  cwd="$(jq -r '.cwd // ""' <<<"$input" 2>/dev/null)"
  path="${cwd:-$PWD}/$path"
fi

decide() {
  jq -nc --arg d "$1" --arg r "$2" \
    '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: $d, permissionDecisionReason: $r}}'
  exit 0
}

case "$path" in
  */iOS/Local.env) decide deny "iOS/Local.env holds the person's bundle ID and Apple team. They edit it themselves." ;;
  */iOS/BroskiPhone.xcodeproj/*) decide deny "The Xcode project is generated by XcodeGen: change iOS/project.yml instead." ;;
  "$HOME/Library/Mobile Documents/com~apple~CloudDocs/Broski"/* | "$HOME/Broski"/*)
    decide deny "That's the person's real Broski folder. Change data through the app; tests and checks use a temporary folder." ;;
  "$HOME/Library/Application Support/Broski"/*) decide deny "That folder holds the API keys and the app's backups. Agents don't write there." ;;
  /Applications/*) decide deny "Installed apps change only through scripts/install-mac.sh." ;;
esac

base="${path##*/}"
if [[ "$base" =~ ^\.env(\..+)?$ && ! "$base" =~ ^\.env\.(example|sample|template)$ ]] || [[ "$base" =~ \.(db|sqlite|sqlite3)$ ]]; then
  decide deny "$base is a secret or database file. Broski's rules: never read or write .env* or *.db files."
fi

# The guardrails themselves: an agent loosening its own checks is the failure they exist to stop.
case "${path#"$BROSKI_ROOT"/}" in
  .claude/settings.json | .githooks/* | scripts/agent/* | scripts/check-secrets.sh)
    decide ask "This changes Broski's guardrails (agent hooks, git hooks, the secret scan). Approve only if you asked for it." ;;
esac
exit 0
